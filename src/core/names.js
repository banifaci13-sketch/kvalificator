export const NAMES = new Set(LIST.split(/\s+/).filter(Boolean));

const key = (w) => String(w ?? '').toLowerCase().replace(/ё/g, 'е');

/** Есть ли такое имя (одно слово или двойное «Мария-Луиза» — по первой части). */
export function isKnownName(word) {
  const k = key(word);
  return NAMES.has(k) || (k.includes('-') && NAMES.has(k.split('-')[0]));
}

// отчество: «Сергеевна», «Петрович», «Ильич»
export const isPatronymic = (w) => /^[а-яё]{3,}(?:ович|евич|ич|овна|евна|ична|инична)$/i.test(String(w ?? ''));
// фамилия: «Петрова», «Иванов», «Сухорукий», «Ковальчук», «Гогия»
export const isSurname = (w) => /^[а-яё-]{3,}(?:ов|ев|ёв|ин|ын|ова|ева|ёва|ина|ына|ский|ская|цкий|цкая|ой|ая|ко|ук|юк|чук|енко|дзе|швили|ян|янц|иани|ия|их|ых|ман|берг|штейн)$/i.test(String(w ?? ''));

/**
 * Похоже ли незнакомое слово на имя — только когда клиент прямо представился («меня зовут Аэлита»):
 * буквы одного алфавита, есть гласные, нет «ааааа», «ывфывф» и пяти согласных подряд.
 */
export function plausibleName(word) {
  const w = key(word);
  if (!/^(?:[а-я]{2,15}|[a-z]{2,15})(?:-(?:[а-я]{2,15}|[a-z]{2,15}))?$/.test(w)) return false;
  if (!/[аеиоуыэюяaeiouy]/.test(w)) return false;
  if (/(.)\1\1/.test(w)) return false;
  if (/[бвгджзйклмнпрстфхцчшщъьbcdfghjklmnpqrstvwxz]{4,}/.test(w)) return false;
  // сочетания с клавиатуры: «фыва», «йцук», «asdf», «qwer»
  if (/фыв|ыва|йцу|цук|уке|апр|про(?=лд)|олд|лдж|ячс|чсм|asd|sdf|dfg|qwe|wer|ert|zxc|xcv|jkl/.test(w)) return false;
  return !NOT_A_NAME.has(w);
}

