// Не клиент: предлагают свои услуги, сотрудничество, рекламу на своей площадке, присылают резюме
// или спамят. Таким квалификатор вежливо отвечает «пишите на почту» и заканчивает разговор —
// менеджерам заявка не уходит.
//
// Важно не задеть клиентов: «пришлите КП», «предложите бюджет», «мы агентство, ищем подрядчика
// на директ», «нужна реклама для криптобиржи» — это заявки. Поэтому ищем именно предложение
// от первого лица («предлагаем вам», «увеличим ваши продажи», «реклама в нашем канале»).

const norm = (t) => String(t ?? '').toLowerCase().replace(/ё/g, 'е');

const OFFER = [
  // «предлагаем / хотим предложить / готовы предложить … вам, услуги, сотрудничество»
  /(?:^|[^а-я])(?:предлагаем|предлагаю|можем\s+предложить|хотим\s+предложить|хочу\s+предложить|хотели\s+бы\s+предложить|хотел\S*\s+бы\s+предложить|готовы\s+предложить|рады\s+предложить)(?:\s+\S+){0,3}?\s+(?:вам|вашей|вашему|вашего|ваш|услуг|сотрудничеств|партнерств|свои|свой|наш|размещени|рекламу\s+(?:в|на|у)|лид|трафик|базу|базы|выгодн|бесплатн|интеграц|сервис|продукт|решени|платформ|программ|аутсорс)/,
  /(?:^|[^а-я])(?:предлагаем|предлагаю)\s+(?:сотрудничество|партнерство|услуги|свои|нашу|наши|наш)/,
  // «ищем партнёров», «приглашаем к сотрудничеству», «предложение о сотрудничестве»
  /(?:ищем|ищу|приглашаем|приглашаю)\s+(?:\S+\s+){0,2}(?:партнер|агентств\S*\s+для\s+сотрудничеств|к\s+сотрудничеств|в\s+партнер)/,
  /предложени\S*\s+(?:о|по|для)\s+(?:сотрудничеств|партнерств)|(?:коммерческ\S*\s+предложени\S*|кп)\s+для\s+(?:вас|вашего|вашей)|готовы\s+к\s+сотрудничеств\S*\s+с\s+вами/,
  // «увеличим ваши продажи», «выведем ваш сайт в топ», «заметили ошибки на вашем сайте»
  /(?:увеличим|продвинем|выведем|поднимем|приведем|привлечем|сделаем|настроим|улучшим|ускорим|поможем\s+(?:вам|увеличить|вашему|вашей))\s+(?:\S+\s+){0,2}(?:ваш|вам|вас)/,
  /(?:заметили|нашли|обнаружили|увидели|проанализировали)\s+(?:\S+\s+){0,3}(?:на\s+)?(?:вашем|ваш|у\s+вас)\s+(?:сайт|аккаунт|групп|канал|реклам|кабинет)/,
  // продают рекламу у себя: «реклама в нашем канале», «размещение у нас», «продаём лиды»
  /реклам\S*\s+(?:в|на|у)\s+(?:нашем|нашей|наших|нас\s+в)\s+\S*?(?:канал|паблик|групп|журнал|издани|блог|сайт|площадк|сообществ|приложени|сети|экран|медиа)/,
  /размещени\S*\s+(?:рекламы\s+)?(?:у\s+нас|в\s+нашем|в\s+нашей|на\s+нашем|на\s+нашей)/,
  /(?:продаем|продаю|поставляем|поставляю|продажа)\s+(?:\S+\s+)?(?:лид|трафик|заявк|баз|подписчик|аккаунт|отзыв|ссылк)/,
  /наш\S*\s+(?:агентство|студия|компания|команда|сервис|платформа)\s+(?:\S+\s+){0,4}(?:предлага|оказыва|готов\S*\s+(?:взять|предлож|помочь\s+вам))/,
  /(?:я|мы)\s+(?:—\s+|-\s+)?(?:\S+\s+){0,3}(?:таргетолог|директолог|seo.?специалист|сеошник|smm.?специалист|смм.?специалист|маркетолог|дизайнер|разработчик|фрилансер|копирайтер|веб.?студия|digital.?агентство|агентство)\S*[,\s]+(?:\S+\s+){0,4}(?:предлага|ищу\s+(?:клиент|проект|заказ|работ)|возьму\s+(?:проект|заказ)|готов\S*\s+(?:взять|сотрудничать|работать\s+с\s+вами)|могу\s+(?:взять|помочь\s+вам))/,
  /(?:white\s*label|субподряд|на\s+субподряд|аутстаф|аутстафф)\S*\s+(?:\S+\s+){0,3}(?:предлага|готов|можем|для\s+вас|вашим\s+клиентам)/,
  /(?:агентское|партнерское)\s+вознаграждени|реферальн\S*\s+(?:программ|выплат)\s+для\s+(?:вас|агентств)/,
];

// клиент: ему что-то нужно от агентства
const CLIENT_NEED = /(?:нужн|нужен|нужна|требуется|хотим|хочу|ищем\s+(?:агентств|подрядчик|исполнител|специалист)|интересует)\S*\s+(?:\S+\s+){0,3}(?:реклам|продвиж|директ|таргет|seo|сео|smm|смм|сайт|лендинг|маркетинг|трафик|заявк|лид|аналитик|контекст)/;
const ADDRESSED_TO_US = /(?:^|[^а-я])(?:вам|вас|ваш\S*)(?:[^а-я]|$)|сотрудничеств|партнерств|субподряд/;

const JOB = /резюме|ваканси|ищу\s+работу|ищу\s+подработк|хочу\s+(?:у\s+вас\s+)?работать|хочу\s+(?:к\s+вам|в\s+вашу\s+команду|в\s+ваше\s+агентство)|возьмите\s+(?:меня|на\s+работу|в\s+команду)|стажировк|устроиться\s+(?:к\s+вам|на\s+работу)|трудоустро|соискател|открыт\S*\s+позици|(?:есть|нужен|нужны|ищете)\s+(?:ли\s+)?(?:у\s+вас\s+)?(?:сотрудник|специалист)\S*\s+в\s+(?:штат|команду)|портфолио\s+(?:прилагаю|по\s+ссылке)/;

const SPAM = [
  /казино|casino|букмекер|ставки\s+на\s+спорт|игровые\s+автоматы|слоты|1xbet|вулкан\s+(?:клуб|казино)/,
  /заработ\S*\s+(?:от|до)?\s*\d|заработок\s+(?:в\s+интернете|без\s+вложений|на\s+дому|онлайн)|пассивн\S*\s+доход|без\s+вложений|быстрые\s+деньги|доход\s+от\s+\d+\s*(?:\$|руб|₽|тыс|к)\s+в\s+(?:день|неделю)/,
  /(?:пиши|пишите|напиши|напишите)\s+(?:мне\s+)?в\s+(?:лс|личку|личные\s+сообщения|директ\s+инст)|переходи\S*\s+по\s+ссылке|жми\s+на\s+ссылку|только\s+сегодня\s+скидк/,
  /порно|эскорт|интим|виагр|viagra|наркот|закладк|обнал|прогон\S*\s+(?:по|хрумер)|хрумер|xrumer|массов\S*\s+рассылк\S*\s+(?:по|для)|базы?\s+(?:email|e-mail|номеров|телефонов)\s+(?:для|на\s+продаж|продаю|продаем)/,
  /https?:\/\/\S+[\s\S]*https?:\/\/\S+[\s\S]*https?:\/\//,
];

/**
 * Кто пишет: 'offer' — предлагают свои услуги или сотрудничество, 'job' — ищут работу,
 * 'spam' — спам; null — похоже на клиента.
 */
export function notClientKind(text) {
  const t = norm(text);
  if (!t.trim()) return null;
  if (SPAM.some((r) => r.test(t))) return 'spam';
  if (JOB.test(t)) return 'job';
  if (!OFFER.some((r) => r.test(t))) return null;
  // «Мы предлагаем услуги клининга, нужна реклама» — клиент рассказывает о своём бизнесе:
  // предложение засчитываем, только если оно обращено к нам (вам, ваш, сотрудничество)
  if (CLIENT_NEED.test(t) && !ADDRESSED_TO_US.test(t)) return null;
  return 'offer';
}

// цитата ИИ про «не клиент» засчитывается, только если в ней есть такие слова — модель не должна
// отправить на почту клиента, который просто рассказал о себе
export const NOT_CLIENT_HINT = /предлаг|сотрудничеств|партнер|наш\S*\s+(?:услуг|канал|площадк|агентств|студи|сервис)|резюме|ваканси|работ\S*\s+у\s+вас|заработ|казино|в\s+лс|в\s+личку|реклам\S*\s+(?:в|на|у)\s+наш|продаем|поставляем|ваш\S*\s+(?:сайт|продаж|бизнес)/;

export const DEFAULT_OFFERS_EMAIL = 'info@soroka-marketing.ru';

/** Ответ тем, кто пишет не с заявкой. */
export function notClientText(kind, email = DEFAULT_OFFERS_EMAIL) {
  if (kind === 'job') return `Спасибо за интерес к агентству! Этот чат — для заявок на наши услуги. Резюме и вопросы о работе, пожалуйста, присылайте на почту ${email}.`;
  if (kind === 'spam') return `Этот чат — для заявок на наши услуги. Другие предложения, пожалуйста, присылайте на почту ${email}.`;
  return `Спасибо за предложение! Этот чат — для заявок на наши услуги. Предложения о сотрудничестве, рекламе и партнёрстве, пожалуйста, присылайте на почту ${email} — их рассмотрят ответственные сотрудники.`;
}
