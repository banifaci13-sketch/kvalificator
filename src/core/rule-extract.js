/** Когда хотят начать: слова («срочно», «через месяц») или месяц / сезон относительно сегодняшнего дня. */
export function startFrom(text, now = new Date()) {
  const t = String(text ?? '');
  const byWords = START_WORDS.find(([, r]) => r.test(t));
  if (byWords) return byWords[0];
  // «через 2 недели», «через 3 месяца», «через 10 дней»
  const rel = /через\s+(\d+|[а-я]+)\s+(дн|недел|месяц)/iu.exec(t);
  if (rel) {
    const n = /^\d+$/.test(rel[1]) ? Number(rel[1]) : NUM_SMALL[rel[1].toLowerCase().replace(/ё/g, 'е')] ?? NUM_SMALL[rel[1].toLowerCase().slice(0, 3)];
    if (n != null) {
      const days = n * (rel[2].startsWith('дн') ? 1 : rel[2].startsWith('недел') ? 7 : 30);
      return days <= 10 ? 'asap' : days <= 31 ? 'month' : days <= 95 ? 'quarter' : 'exploring';
    }
  }
  const m = MONTH_RE.exec(t);
  const season = !m && SEASON_RE.exec(t);
  let month = null;
  if (m) month = Number(Object.entries(m.groups).find(([, v]) => v)[0].slice(1));
  else if (season) {
    const w = season[0].toLowerCase();
    month = /весн/.test(w) ? 2 : /лет/.test(w) ? 5 : /осен/.test(w) ? 8 : /после|в\s+новом|с\s+нового/.test(w) ? 0 : 11;
  }
  if (month == null) return null;
  const diff = (month - now.getMonth() + 12) % 12;
  return diff <= 1 ? 'month' : diff <= 3 ? 'quarter' : 'exploring';
}

