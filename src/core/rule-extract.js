/** Разбор рассказа клиента по правилам. now — «сегодня» для «в сентябре», «к лету». */
export function ruleExtract(text, { now = new Date() } = {}) {
  const t = String(text ?? '');
  const out = {};
  const { services } = serviceEvidence(t);
  if (services.length) out.services = services;
  const rub = moneyFromText(t);
  const budgetToUs = BUDGET_TO_US_RE.test(t);
  if (budgetToUs || PROPOSAL_RE.test(t)) out.proposal = true;
  if (rub != null) out.budget = budgetBucket(rub);
  else if (budgetToUs || BUDGET_UNKNOWN_RE.test(t)) out.budget = 'unknown';
  const start = startFrom(t, now);
  if (start) out.start = start;
  const site = siteFrom(t);
  if (site) out.site = site;
  const legal = LEGAL_RE.exec(t);
  if (legal) out.company = legal[0].trim();
  const exp = experienceFrom(t);
  if (exp) out.agency_experience = exp;
  const lower = t.toLowerCase().replace(/ё/g, 'е');
  const industry = firstHit(INDUSTRY, lower);
  if (industry) out.industry = industry;
  const b2b = MARKET_B2B.test(lower);
  const b2c = MARKET_B2C.test(lower);
  if (b2b || b2c) out.market = b2b && b2c ? 'both' : b2b ? 'b2b' : 'b2c';
  const geo = GEO.find(([, r]) => r.test(lower))?.[0];
  if (geo) out.geography = geo;
  const role = firstHit(ROLE, lower);
  if (role) out.role = role;
  const decision = firstHit(DECISION, lower);
  if (decision) out.decision_maker = decision;
  return out;
}

// ---------- ответ на уточнение по пунктам ----------

const YES_RE = /^\s*(?:да|ага|угу|конечно|есть|работали|работаем|был[иао]?|сотрудничали)(?![а-я])/iu;
const NO_RE = /^\s*(?:(?:нет|неа|никогда|впервые|отсутству\S*)(?![а-я])|не\s|ни\s+с\s+кем|пока\s+нет)/iu;
const DONT_KNOW_RE = /не\s*знаю|затрудня|не\s+определ|пока\s+нет|сложно\s+сказать|обсуд|не\s+скажу|не\s+готов|вопрос|\?/iu;

/** Разбор одного пункта ответа по смыслу вопроса («нет» про подрядчика — «впервые», про сайт — «нет сайта»). */
function answerFor(key, part, now) {
  const p = part.trim();
  if (!p) return {};
  switch (key) {
    case 'services': {
      const { services } = serviceEvidence(p);
      return services.length ? { services } : {};
    }
    case 'budget': {
      const rub = moneyFromText(p);
      if (rub != null) return { budget: budgetBucket(rub) };
      if (BUDGET_TO_US_RE.test(p) || /от\s+вас|ваше\s+усмотрен|предлож|рекоменд/iu.test(p)) return { budget: 'unknown', proposal: true };
      // голое число в ответе на вопрос о бюджете — тысячи («150» → 150 000)
      const bare = /^\s*(?:около|примерно|порядка|до|от|~)?\s*(\d{2,4})\s*(?:в\s+мес\S*)?\s*$/iu.exec(p);
      if (bare) return { budget: budgetBucket(Number(bare[1]) * 1000 - (/до/i.test(p) ? 1 : 0)) };
      if (DONT_KNOW_RE.test(p) || NO_RE.test(p) || BUDGET_UNKNOWN_RE.test(p)) return { budget: 'unknown' };
      return {};
    }
    case 'start': {
      const s = startFrom(p, now);
      if (s) return { start: s };
      if (/^(?:сейчас|сразу|срочно|быстрее|скорее|asap|уже)/iu.test(p)) return { start: 'asap' };
      if (DONT_KNOW_RE.test(p)) return { start: 'exploring' };
      return {};
    }
    case 'agency_experience': {
      const e = experienceFrom(p);
      if (e) return { agency_experience: e };
      if (NO_RE.test(p)) return { agency_experience: 'none' };
      if (YES_RE.test(p)) return { agency_experience: /сейчас|работаем|текущ/iu.test(p) ? 'current' : 'past' };
      return {};
    }
    case 'dissatisfaction':
      return p.length >= 3 ? { dissatisfaction: p.slice(0, 300) } : {};
    case 'site': {
      const s = siteFrom(p);
      if (s) return { site: s };
      if (NO_RE.test(p) || /^(?:-|—)$/.test(p)) return { site: NO_SITE };
      // название бренда или магазина словами — тоже ответ
      return p.length >= 2 && p.length <= 100 ? { site: p } : {};
    }
    default:
      return {};
  }
}

/**
 * Ответ на уточнение «1) … 2) … 3) …»: по номерам, по строкам или через запятую/точку с запятой —
 * если частей столько же, сколько вопросов. Каждый пункт разбирается по смыслу своего вопроса.
 */
export function clarifyExtract(text, asked = [], { now = new Date() } = {}) {
  const t = String(text ?? '').trim();
  if (!t || !asked.length) return {};
  let parts = null;
  const numbered = [...t.matchAll(/(?:^|[\s,;])(\d)\s*[).:-]\s*/g)];
  if (numbered.length >= 2 || (asked.length === 1 && numbered.length === 1)) {
    parts = new Array(asked.length).fill('');
    numbered.forEach((m, i) => {
      const n = Number(m[1]) - 1;
      const end = numbered[i + 1]?.index ?? t.length;
      if (n >= 0 && n < asked.length) parts[n] = t.slice(m.index + m[0].length, end).replace(/[;,.\s]+$/, '');
    });
  } else if (asked.length === 1) {
    parts = [t];
  } else {
    for (const sep of [/\n+/, /\s*;\s*/, /\s*,\s*/]) {
      const p = t.split(sep).map((x) => x.trim()).filter(Boolean);
      if (p.length === asked.length) {
        parts = p;
        break;
      }
    }
  }
  if (!parts) return {};
  const out = {};
  asked.forEach((key, i) => Object.assign(out, answerFor(key, parts[i] ?? '', now)));
  return out;
}

// ---------- имя ----------

const GREET_RE = /^(?:здравствуйте|здравствуй|добрый\s+(?:день|вечер)|доброе\s+утро|доброй\s+ночи|день\s+добрый|приветствую|привет|хай|салют|hello|hi)(?![а-яa-z])[\s,.!—-]*/iu;
const NAME_WORD = '[А-ЯЁA-Zа-яёa-z][а-яёa-z]+(?:-[А-ЯЁа-яё][а-яё]+)?';
const NAME_INTRO_RE = new RegExp(`(?:меня\\s+зовут|зовут\\s+меня|мо[её]\\s+имя|можно\\s+просто|обращайтесь\\s+(?:ко\\s+мне\\s+)?(?:по\\s+имени\\s+)?|на\\s+связи|с\\s+вами|(?:^|[\\s,])это)\\s*[:—-]?\\s*(${NAME_WORD}(?:\\s+${NAME_WORD})?)`, 'iu');
const SELF_RE = /(?:^|[\s,])[яЯ]\s*[—-]?\s*([А-ЯЁA-Z][а-яёa-z]+(?:\s+[А-ЯЁA-Z][а-яёa-z]+)?)/u;
// слова, которые пишут рядом с именем, но это не имя
const NOT_NAME = /^(?:компания|компании|директор|менеджер|маркетолог|собственник|владелец|представитель|руководитель|сотрудник|ассистент|помощник|агентство|ооо|ип|ао|пао|зао|из|от|по|для|меня|зовут|я|это|мы|нас|наш|наша|здравствуйте|привет|добрый|день|вечер|утро|спасибо|да|нет|ок|окей|хорошо)$/iu;
const TASK_HINT_RE = /нуж[енанo]|хотим|хочу|интересу|требуется|реклам|продвиж|бюджет|сайт|заявк|клиент|продаж|магазин|запуст|настро|помогите|\d{3,}/iu;
const cap = (w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase();

/**
 * Имя из ответа на «Как к вам обращаться?»: «Анна», «меня зовут анна», «Здравствуйте, это Игорь из ООО Ромашка».
 * task — клиент сразу написал задачу («Игорь, нужен директ для автосервиса»): её не теряем.
 */
export function nameFrom(text) {
  const raw = String(text ?? '').trim();
  const body = raw.replace(GREET_RE, '').trim();
  const words = body.split(/\s+/).filter(Boolean);
  const task = words.length >= 8 || serviceEvidence(body).services.length > 0 || TASK_HINT_RE.test(body);
  const fmt = (n) => n.split(/\s+/).filter((w) => !NOT_NAME.test(w)).slice(0, 2).map((w) => w.split('-').map(cap).join('-')).join(' ') || null;
  const intro = NAME_INTRO_RE.exec(body) ?? SELF_RE.exec(body);
  if (intro) {
    const name = fmt(intro[1]);
    if (name) return { name, task };
  }
  // «Анна», «Анна Петрова», «Анна, маркетолог», «Игорь, нужен директ» — имя первым словом
  const first = /^([А-ЯЁA-Zа-яёa-z][а-яёa-z]+(?:-[А-ЯЁа-яё][а-яё]+)?)(?:\s+([А-ЯЁA-Z][а-яёa-z]+))?(?=[\s,.!—-]|$)/u.exec(body);
  // при задаче имя — только отдельным словом перед запятой или тире: «Игорь, нужен директ», но не «Нужна реклама…»
  const separated = first && (!task || /^\s*[,—-]/.test(body.slice(first[0].length)));
  if (first && separated && !NOT_NAME.test(first[1]) && !TASK_HINT_RE.test(first[1])) {
    const second = first[2] && !NOT_NAME.test(first[2]) && !task ? ` ${first[2]}` : '';
    const name = fmt(first[1] + second);
    if (name) return { name, task };
  }
  return { name: null, task };
}

