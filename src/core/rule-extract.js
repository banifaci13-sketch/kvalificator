const SITE_RE = new RegExp(`(?<![\\p{L}\\p{N}@.-])(?:https?:\\/\\/)?(?:www\\.)?[\\p{L}\\p{N}-]+(?:\\.[\\p{L}\\p{N}-]+)*\\.(?:${TLD})(?![\\p{L}\\p{N}])(?:\\/[^\\s,;]*)?`, 'iu');
