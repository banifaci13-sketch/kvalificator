// Сайт и маркетплейсы клиенты часто просто упоминают («ведём трафик на сайт», «продаём на маркетплейсах») —
// это не заказ услуги. Засчитываем, только если есть намерение: сайт — сделать / переделать,
// маркетплейсы — в той же части фразы «нужно», «хотим», «продвигать», «выйти на»…
const INTENT_RE = /нуж|хоти|хочу|хотел|надо|требу|интерес|планир|продвиг|продвиж|раскрут|вывести|выйти|выход\S* на|зайти|запуст|подключ|настро|помогите|помочь|увелич|рост|рос(?:ли|ла|ло)|подн|нарастить|сделать|начать|реклам|больше\s+продаж/i;
const MARKETPLACE_RE = SERVICE_WORDS.find(([k]) => k === 'marketplaces')[1];
// Таргет — реклама в соцсетях и мессенджерах. Медийную (охватную, баннерную) ИИ путает с таргетом,
// а «ретаргетинг» — это контекст: таргет — только по словам таргета.
const TARGET_RE = SERVICE_WORDS.find(([k]) => k === 'target')[1];
const clauses = (t) => String(t ?? '').split(/(?<=[.!?\n;])\s+|\n+|\s*,\s*/);
const SERVICE_GUARD = {
  site: (t, named) => SITE_INTENT_RE.test(t) || (named?.products ?? []).some((id) => /^site_/.test(id)),
  target: (t, named) => TARGET_RE.test(t) || (named?.products ?? []).some((id) => /^target_/.test(id)),
  marketplaces: (t) => clauses(t).some((x) => MARKETPLACE_RE.test(x) && INTENT_RE.test(x)),
};

/**
 * Услуги, которые клиент назвал: словарь правил + словарь прайса по подготовленному тексту
 * (без отказов, с исправленными опечатками). Сайт, маркетплейсы и таргет — только при намерении.
 */
export function serviceEvidence(text, pricing = null) {
  const rt = recognitionText(text);
  const named = pricing?.detect?.(rt) ?? { services: [], products: [] };
  let services = [...new Set([...SERVICE_WORDS.filter(([, r]) => r.test(rt)).map(([v]) => v), ...named.services])];
  services = services.filter((s) => !SERVICE_GUARD[s] || SERVICE_GUARD[s](rt, named));
  // «консультация» — только если ничего конкретного не названо
  if (services.some((s) => s !== 'consult')) services = services.filter((s) => s !== 'consult');
  // продукты отброшенных направлений («есть лендинг» — не заказ лендинга) — тоже не в счёт
  const products = named.products.filter((id) => {
    const svc = pricing?.serviceOf?.(id);
    return !svc || services.includes(svc);
  });
  return { services, products, text: rt };
}

/** Убрать услуги, которые клиент только упомянул, а не заказал. */
export const wantedServices = (list, text) => {
  const rt = recognitionText(text);
  return (list ?? []).filter((s) => !SERVICE_GUARD[s] || SERVICE_GUARD[s](rt));
};

