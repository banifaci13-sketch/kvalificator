const HANDLE_RE = /(?:канал\S*|тг|телеграм\S*|telegram|инст\S*|instagram|аккаунт\S*|групп\S*|сообществ\S*|страниц\S*|паблик\S*)\s*:?\s*(@[a-z0-9_.]{4,32})/iu;
const NO_SITE_RE = /(?:сайта|сайт)\s+(?:у\s+нас\s+)?(?:пока\s+|еще\s+|ещё\s+|вообще\s+)?(?:нет|отсутству)|нет\s+(?:пока\s+|еще\s+|ещё\s+)?(?:своего\s+)?сайта|без\s+сайта|сайт\S*\s+(?:в\s+разработке|делаем|только\s+делаем|ещё\s+не|еще\s+не|не\s+готов)|сайта\s+не\s+(?:имеем|существует|было)/iu;
export const NO_SITE = 'нет сайта';
const LEGAL_RE = /(?<![\p{L}\p{N}])(?:ООО|ИП|АО|ПАО|ЗАО|НКО|ОАО|ТОО)\s+(?:«[^»]{2,60}»|"[^"]{2,60}"|[А-ЯЁA-Z][\wА-Яа-яЁё-]{1,40}(?:\s+[А-ЯЁA-Z][\wА-Яа-яЁё-]{1,40}){0,2})/u;

export function siteFrom(text) {
  const t = String(text ?? '');
  const site = SITE_RE.exec(t);
  if (site) return site[0].replace(/[.,;)]+$/, '');
  const handle = HANDLE_RE.exec(t);
  if (handle) return handle[1];
  if (NO_SITE_RE.test(t)) return NO_SITE;
  return null;
}

