/** Суммы словами и сленгом → цифрами: «двести пятьдесят тысяч», «пол ляма», «сотка», «1.5кк». */
export function moneyWords(text) {
  return String(text ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/(?<![а-я])пол[\s-]?(?:ляма|лимона|миллиона|млн)(?![а-я])/giu, '500 тысяч')
    .replace(/(?<![а-я])полмиллиона(?![а-я])/giu, '500 тысяч')
    .replace(/(?<![а-я])(?:пару|пара)\s+сотен\s+(?:тысяч|тыс)/giu, '200 тысяч')
    .replace(/(?<![а-я\d]\s?)(?<![\d.,]\s)(?<![а-я])(?:сотк[аиуе]|сотен\s+тысяч)(?![а-я])/giu, '100 тысяч')
    .replace(NUMWORDS_RE, (m) => String(m.split(/\s+/).reduce((n, w) => n + (UNITS[w] ?? 0), 0)))
    // «миллион», «лям» без числа — один
    .replace(/(?<![\d.,]\s?)(?<![а-я])(миллион|лям)(?![а-я])/giu, '1 $1');
}

const MONEY_RE = /(\d{1,3}(?:[\s  ]\d{3})+|\d+(?:[.,]\d+)?)\s*(млн\S*|миллион\S*|лям\S*|лимон\S*|кк(?![а-я])|kk(?![a-z])|тыс\S*|тыщ\S*|т\.\s?р\.?|тр(?![а-я])|тыр(?![а-я])|косар\S*|к(?![а-я])|k(?![a-z]))?\s*(₽|руб\S*|р\.?(?![а-я])|rub)?/giu;
// после числа — не деньги: «1000 заявок», «50 000 подписчиков», «3 месяца», «20%»
const QTY_AFTER = /^\s*(?:%|процент|заяв|лид|клиент|подписчик|посетител|человек|чел(?![а-я])|товар|sku|позици|штук|шт(?![а-я])|клик|показ|просмотр|переход|заказ|продаж|сотрудник|магазин|филиал|точ[еки]|км|м2|кв\.?\s?м|квадрат|метр|дн|день|недел|месяц|лет|год|раз(?![а-я])|звонк|обращени|визит|сесси|юнит|единиц|объект|квартир|дом|литр|кг|тонн|мест|номер|отзыв|карточ|артикул|наименован|канал|групп|аккаунт|город|регион|стран)/iu;
// перед числом — не рекламный бюджет: оборот, чек, выручка, цена товара, ИНН
const NOT_BUDGET_BEFORE = /(?:чек\S*|выручк\S*|оборот\S*|прибыл\S*|зарплат\S*|оклад\S*|капитализ\S*|инн|огрн|кпп|телефон\S*|тел\.?|номер\S*|артикул\S*|себестоим\S*|марж\S*|наценк\S*|ltv|ср\.?\s?чек|стоим\S*\s+(?:товар|продукт|квартир|дом|тур|авто|машин|объект|курс|абонемент)\S*|(?:товар|продукт|квартир|дом|тур|авто|машин|объект|курс|абонемент)\S*\s+(?:стоим\S*|стоят|стоит|по\s+цене|ценой|от)|продаем\s+на|продаж\S*\s+(?:на|в)\s+(?:месяц\s+)?(?:на)?)\s*(?:от|до|около|примерно|порядка|~)?\s*$/iu;
const BUDGET_HINT = /бюджет|трат|потрат|вклад|выдел|готов|расход|в\s+месяц|ежемесячн|в\s+мес|\/\s?мес|на\s+рекламу|на\s+продвижение|на\s+маркетинг|рекламн|на\s+(?:директ|таргет|seo|сео|smm|смм|контекст)|в\s+(?:директ|таргет)|оплат|инвест/iu;
const PER_YEAR = /^\s*(?:₽|руб\S*)?\s*(?:в|на|за|\/)\s*(год|квартал|полгода|недел|день|сутки)/iu;
const YEAR_BEFORE = /(?:годов\S*|в\s+год|на\s+год|за\s+год|квартальн\S*|на\s+квартал|в\s+квартал)\s+(?:\S+\s+){0,3}$/iu;

/** Рекламный бюджет в рублях в месяц: «300 000», «300к», «1,5 млн», «до 100 тыс», «пол ляма», «1,2 млн в год». */
export function moneyFromText(text) {
  // телефоны, даты, ссылки — не суммы
  const t = moneyWords(text)
    .replace(/(?:\+7|(?<!\d)8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}/g, ' ')
    .replace(/\+\d[\d\s()-]{8,}\d/g, ' ')
    .replace(/\d{1,2}[./]\d{1,2}[./]\d{2,4}/g, ' ')
    .replace(/\S+\.(?:ru|com|рф|net|org|me|io|pro|su)\S*/giu, ' ');
  const found = [];
  for (const m of t.matchAll(MONEY_RE)) {
    const unit = (m[2] ?? '').toLowerCase();
    let v = Number(m[1].replace(/[\s  ]/g, '').replace(',', '.'));
    if (!Number.isFinite(v)) continue;
    if (/^(?:млн|миллион|лям|лимон|кк|kk)/.test(unit)) v *= 1e6;
    else if (/^(?:тыс|тыщ|т\.|тр|тыр|косар|к|k)/.test(unit)) v *= 1e3;
    // «на 3 месяца», «2 канала», годы — не деньги: без единиц берём только крупные суммы
    if (!unit && !m[3] && v < 10_000) continue;
    const after = t.slice(m.index + m[0].length);
    if (QTY_AFTER.test(after)) continue;
    const before = t.slice(Math.max(0, m.index - 40), m.index);
    if (NOT_BUDGET_BEFORE.test(before)) continue;
    // «до 100 тыс.» — меньше 100 тыс.
    if (/(?:^|\s)до\s*$/i.test(before)) v -= 1;
    // за год / квартал / неделю — в месяц
    const per = PER_YEAR.exec(after)?.[1]?.toLowerCase() ?? (YEAR_BEFORE.test(before) ? (/квартал/.test(before) ? 'квартал' : 'год') : null);
    if (per) v = per === 'год' ? v / 12 : per === 'квартал' ? v / 3 : per === 'полгода' ? v / 6 : per.startsWith('недел') ? v * 4.3 : v * 30;
    // сумма рядом со словами про бюджет важнее прочих
    const clause = t.slice(Math.max(0, t.lastIndexOf('.', m.index) + 1, m.index - 80), m.index + m[0].length + 40);
    if (v >= 1000) found.push({ v: Math.round(v), hint: BUDGET_HINT.test(clause) });
  }
  const pool = found.some((f) => f.hint) ? found.filter((f) => f.hint) : found;
  return pool.length ? Math.max(...pool.map((f) => f.v)) : null;
}

/** Сумма в месяц → вариант бюджета из сценария. */
export function budgetBucket(rub) {
  if (rub == null || !Number.isFinite(rub)) return null;
  if (rub < 100_000) return 'lt100k';
  if (rub < 300_000) return '100_300k';
  if (rub < 1_000_000) return '300k_1m';
  if (rub < 3_000_000) return '1m_3m';
  return 'gt3m';
}

