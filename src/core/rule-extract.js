/** Ответ «что главное в выборе исполнителя» → вариант сценария (самое раннее упоминание). */
export function criteriaGuess(text) {
  return firstHit(CRITERIA, String(text ?? '').toLowerCase().replace(/ё/g, 'е'));
}
